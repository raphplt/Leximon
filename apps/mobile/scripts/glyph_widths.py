"""Advance widths of the sachet's display font, so that the app can wrap the collection's name
on its ribbon the way the web does, before drawing it in SVG, which never wraps:

    uv run --no-project --with fonttools python -I scripts/glyph_widths.py \
        assets/fonts/Fraunces-ExtraBold.ttf src/screens/play/glyph-widths.ts && pnpm format

Widths are in thousandths of the font size; kerning is left out.
"""
import sys
from pathlib import Path
from fontTools.ttLib import TTFont

font = TTFont(sys.argv[1])
scale = 1000 / font["head"].unitsPerEm
metrics = font["hmtx"].metrics
widths = {
    chr(code): round(metrics[glyph][0] * scale)
    for code, glyph in sorted(font.getBestCmap().items())
    if 0x20 <= code <= 0x17F
}
entries = ",".join(f"{width}" for width in widths.values())
chars = "".join(widths)
escaped = chars.replace("\\", "\\\\").replace('"', '\\"')
Path(sys.argv[2]).write_text(
    "// Generated by scripts/glyph_widths.py from Fraunces-ExtraBold.ttf: do not edit.\n\n"
    "/** The characters measured, in the order of `WIDTHS`. */\n"
    f'const CHARS = "{escaped}";\n'
    "/** Advance widths, in thousandths of the font size. */\n"
    f"const WIDTHS = [{entries}];\n\n"
    "const TABLE = new Map([...CHARS].map((char, index) => [char, WIDTHS[index] ?? 0]));\n"
    "/** The width of an unknown character: the font's average. */\n"
    f"const FALLBACK = {round(sum(widths.values()) / len(widths))};\n\n"
    "/** The width of `text` in Fraunces 800 at `size`, without kerning. */\n"
    "export function displayBoldWidth(text: string, size: number): number {\n"
    "  let total = 0;\n"
    "  for (const char of text) total += TABLE.get(char) ?? FALLBACK;\n"
    "  return (total * size) / 1000;\n"
    "}\n"
)
print(len(widths), "characters")
